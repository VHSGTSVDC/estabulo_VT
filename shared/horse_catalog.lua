local function pretty(v)
    v=v:gsub('_PC$',''):gsub('([a-z])([A-Z])','%1 %2'):gsub('(%a)(%d)','%1 %2'):gsub('_',' ')
    return v
end
local function parseModel(model)
    local rest=model:gsub('^A_C_Horse_',''):gsub('^A_C_','')
    if model=='A_C_HorseMule_01' then return 'Mula','Padrão' end
    if model=='A_C_HorseMulePainted_01' then return 'Mula Pintada','Padrão' end
    if model=='A_C_Donkey_01' then return 'Jumento','Padrão' end
    local breed,coat=rest:match('^([^_]+)_(.+)$'); breed=breed or rest; coat=coat or 'Padrão'
    return breedNames[breed] or pretty(breed),pretty(coat)
end
local existing={}; for _,h in ipairs(LRRPHorseCatalog) do existing[h.model]=true end
for _,model in ipairs(officialModels) do
    if not existing[model] then
        local breed,coat=parseModel(model); local key=model:match('^A_C_Horse_([^_]+)') or breed
        local currency=premiumBreeds[key] and 1 or 0; local price=currency==1 and 9 or 650
        LRRPHorseCatalog[#LRRPHorseCatalog+1]={model=model,breed=breed,coat=coat,label=breed..' '..coat,price=price,currency=currency}
        existing[model]=true
    end
end

function LRRPHorseFind(model)
    for _, horse in ipairs(LRRPHorseCatalog) do
        if horse.model == model then return horse end
    end
    return nil
end


